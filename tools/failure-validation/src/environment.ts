import assert from "node:assert/strict";
import { mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import type { Builtin } from "./builtins.ts";

export const ENVIRONMENT_PATH = new URL("../../../env/testnet.ak", import.meta.url);
export const GENERATED_START = "// BEGIN GENERATED FAILURE VALIDATION";
export const GENERATED_END = "// END GENERATED FAILURE VALIDATION";

export function generateEnvironment({ name, arity, returnType }: Builtin): string {
  const raw = Array.from({ length: arity }, (_, index) => `raw_${index}`);
  const args = raw.map((_, index) => `arg_${index}`);
  const withArguments = (body: string[]) => arity === 0
    ? ["    arguments.with_arity_0(datum, fn() {", ...body.map((line) => `  ${line}`), "    })"]
    : [`    let ${raw.join(", ")} <- arguments.with_arity_${arity}(datum)`, ...body];
  // Future work: generalize argument preparation beyond ByteArray to support
  // bls12_381_g1_equal and bls12_381_g1_multi_scalar_mul, plus their G2 counterparts.
  // Both apply_builtin and validate_builtin_arguments must perform matching
  // preparation, so decoding failures cannot become proof of the selected builtin's failure.
  const decode = (discard: boolean) => raw.map((value, index) =>
    `    expect ${discard ? "_" : args[index]}: ByteArray = ${value}`,
  );
  const invocation = `builtin_function(${args.join(", ")})`;
  return [
    "// Generated by tools/failure-validation for this build.",
    "",
    `pub const builtin_function: fn(${args.map(() => "ByteArray").join(", ")}) -> ${returnType} =`,
    // A zero-argument function value needs an explicit thunk in Aiken.
    arity === 0 ? `  fn() { builtin.${name}() }` : `  builtin.${name}`,
    "",
    "pub const apply_builtin: fn(Data) -> Bool =",
    "  fn(datum: Data) {",
    ...withArguments([
      ...decode(false),
      ...(returnType === "Bool" ? [`    ${invocation}`] : [`    expect _ = ${invocation}`, "    True"]),
    ]),
    "  }",
    "",
    "/// Check preparation only; byte-string contents are checked by the selected builtin.",
    "pub const validate_builtin_arguments: fn(Data) -> Bool =",
    "  fn(datum: Data) {",
    ...withArguments([...decode(true), "    True"]),
    "  }",
  ].join("\n");
}

export function replaceEnvironment(source: string, generated: string): string {
  const start = source.indexOf(GENERATED_START);
  const end = source.indexOf(GENERATED_END);
  assert(start >= 0 && end > start && start === source.lastIndexOf(GENERATED_START)
    && end === source.lastIndexOf(GENERATED_END), "Expected exactly one ordered pair of failure-validation markers.");
  const startEnd = start + GENERATED_START.length;
  const endEnd = end + GENERATED_END.length;
  const newline = source.slice(startEnd, startEnd + 2) === "\r\n" ? "\r\n" : "\n";
  assert((start === 0 || source[start - 1] === "\n") && source.slice(startEnd, startEnd + newline.length) === newline
    && source[end - 1] === "\n" && (endEnd === source.length || source.slice(endEnd, endEnd + newline.length) === newline),
  "Failure-validation markers must occupy separate lines.");
  return source.slice(0, startEnd) + newline + generated.replace(/\r?\n/g, newline).trim()
    + newline + newline + source.slice(end);
}

export async function withBuiltinEnvironment<T>(
  builtin: Builtin,
  compile: (signal: AbortSignal) => Promise<T>,
  environmentPath: string | URL = ENVIRONMENT_PATH,
): Promise<T> {
  const path = environmentPath instanceof URL ? environmentPath : pathToFileURL(environmentPath);
  const lock = new URL(`${path.href}.failure-validation-lock`);
  try {
    mkdirSync(lock);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "EEXIST") {
      throw new Error(`Another failure-validation build holds ${lock.pathname}.`, { cause: error });
    }
    throw error;
  }
  const temporary = new URL("environment.ak", `${lock.href}/`);
  const controller = new AbortController();
  const interrupt = (signal: "SIGINT" | "SIGTERM") => {
    process.exitCode = signal === "SIGINT" ? 130 : 143;
    controller.abort(new Error(`Build interrupted by ${signal}.`));
  };
  const onInterrupt = () => interrupt("SIGINT");
  const onTerminate = () => interrupt("SIGTERM");
  let original: Buffer | undefined;
  let changed = false;
  try {
    original = readFileSync(path);
    const generated = replaceEnvironment(original.toString("utf8"), generateEnvironment(builtin));
    process.on("SIGINT", onInterrupt);
    process.on("SIGTERM", onTerminate);
    writeFileSync(temporary, generated);
    renameSync(temporary, path);
    changed = true;
    const result = await compile(controller.signal);
    controller.signal.throwIfAborted();
    return result;
  } finally {
    try {
      if (changed && original) {
        writeFileSync(temporary, original);
        renameSync(temporary, path);
      }
    } finally {
      process.off("SIGINT", onInterrupt);
      process.off("SIGTERM", onTerminate);
      rmSync(lock, { recursive: true, force: true });
    }
  }
}
